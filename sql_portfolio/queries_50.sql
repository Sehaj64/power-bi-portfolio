  AND lifetime_sales > 5000
ORDER BY lifetime_sales DESC;
-- Insight: High-priority outreach list. These were heavy spenders who have gone inactive.

-- Q46: Calculate Year-over-Year (YoY) Growth at the Segment level.
-- SQL:
WITH annual_segment_sales AS (
    SELECT 
        c.segment,
        EXTRACT(YEAR FROM s.order_date::date) AS sales_year,
        SUM(s.sales) AS revenue
    FROM sales s
    JOIN customers c ON s.customer_id = c.customer_id
    GROUP BY c.segment, sales_year
)
SELECT 
    curr.segment,
    curr.sales_year,
    ROUND(curr.revenue::numeric, 2) AS current_revenue,
    ROUND(prev.revenue::numeric, 2) AS prior_revenue,
    ROUND(((curr.revenue - prev.revenue) / prev.revenue * 100)::numeric, 2) AS yoy_growth_percent
FROM annual_segment_sales curr
LEFT JOIN annual_segment_sales prev 
    ON curr.segment = prev.segment AND curr.sales_year = prev.sales_year + 1
ORDER BY curr.segment, curr.sales_year;
-- Insight: Identifies market segment expansion rates. Useful for aligning corporate strategy with high-growth segments.

