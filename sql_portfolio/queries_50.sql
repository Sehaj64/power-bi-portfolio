-- Q49: Calculate customer churn rate for a subscription dataset.
-- (Assumes a subscription table schema: customer_id, signup_date, end_date)
-- SQL:
WITH monthly_status AS (
    SELECT 
        customer_id,
        DATE_TRUNC('month', order_date::date) AS active_month
    FROM sales
),
customer_churn AS (
    SELECT 
        active_month,
        COUNT(DISTINCT customer_id) AS active_this_month,
        LEAD(COUNT(DISTINCT customer_id)) OVER (ORDER BY active_month) AS active_next_month
    FROM monthly_status
    GROUP BY active_month
)
SELECT 
    active_month,
    active_this_month,
    ROUND(((active_this_month - COALESCE(active_next_month, active_this_month))::numeric / active_this_month * 100), 2) AS monthly_churn_rate_percent
FROM customer_churn;
-- Insight: Evaluates customer attrition velocity.

-- Q50: Find the total value of sales returned (Sales rows where profit is deeply negative and quantity is negative).
-- SQL:
SELECT 
    EXTRACT(YEAR FROM order_date::date) AS sales_year,
    ROUND(SUM(CASE WHEN profit < 0 AND discount > 0.5 THEN sales ELSE 0 END)::numeric, 2) AS total_returned_sales_value,
    ROUND((SUM(CASE WHEN profit < 0 AND discount > 0.5 THEN sales ELSE 0 END) / SUM(sales) * 100)::numeric, 2) AS return_rate_percent
FROM sales
GROUP BY sales_year;
-- Insight: Quantifies the overall loss rate due to heavy discounts and returns.
