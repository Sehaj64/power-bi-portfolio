-- Q42: Calculate Repeat Purchase Rate within 30 Days.
-- SQL:
WITH first_purchases AS (
    SELECT customer_id, MIN(order_date::date) AS first_date
    FROM sales
    GROUP BY customer_id
),
subsequent_purchases AS (
    SELECT s.customer_id, s.order_date::date AS next_date
    FROM sales s
    JOIN first_purchases fp ON s.customer_id = fp.customer_id
    WHERE s.order_date::date > fp.first_date
)
SELECT 
    COUNT(DISTINCT fp.customer_id) AS total_new_customers,
    COUNT(DISTINCT sp.customer_id) AS returned_in_30_days,
    ROUND((COUNT(DISTINCT sp.customer_id)::numeric / COUNT(DISTINCT fp.customer_id) * 100), 2) AS return_rate_30d
FROM first_purchases fp
LEFT JOIN subsequent_purchases sp ON fp.customer_id = sp.customer_id 
    AND sp.next_date <= fp.first_date + INTERVAL '30 days';
-- Insight: Core product-market fit metric. High repeat rates prove product value and customer satisfaction.

-- Q43: Subscription Retention Rate Month-over-Month (Cohort Retention Matrix style).
-- SQL:
WITH customer_activity AS (
    SELECT DISTINCT
        customer_id,
        DATE_TRUNC('month', order_date::date) AS activity_month
    FROM sales
),
cohort_start AS (
    SELECT 
        customer_id,
        MIN(activity_month) AS cohort_month
    FROM customer_activity
    GROUP BY customer_id
)
SELECT 
    c.cohort_month,
    ROUND(EXTRACT(epoch FROM (a.activity_month - c.cohort_month)) / (30*24*60*60)) AS month_number,
    COUNT(DISTINCT a.customer_id) AS active_customers
FROM customer_activity a
JOIN cohort_start c ON a.customer_id = c.customer_id
GROUP BY c.cohort_month, month_number
ORDER BY c.cohort_month, month_number;
-- Insight: Creates the classic retention heatmap feed. Visualizes customer lifespans across cohort ages.

-- Q44: Find the total revenue from "Returning Customers" vs "New Customers" per year.
-- SQL:
WITH customer_orders AS (
    SELECT 
        customer_id,
        order_id,
        sales,
        EXTRACT(YEAR FROM order_date::date) AS sales_year,
        MIN(EXTRACT(YEAR FROM order_date::date)) OVER (PARTITION BY customer_id) AS acquisition_year
    FROM sales
)
SELECT 
    sales_year,
    ROUND(SUM(CASE WHEN sales_year = acquisition_year THEN sales ELSE 0 END)::numeric, 2) AS new_customer_revenue,
    ROUND(SUM(CASE WHEN sales_year > acquisition_year THEN sales ELSE 0 END)::numeric, 2) AS returning_customer_revenue
FROM customer_orders
GROUP BY sales_year
ORDER BY sales_year;
-- Insight: Evaluates CAC (Customer Acquisition Cost) vs LTV (Lifetime Value). If returning revenue increases, profit margins improve.

-- Q45: Identify the "Most Valued Churn Risks" (No purchases in the last 180 days but historic spending > $5,000).
-- SQL:
WITH customer_profile AS (
    SELECT 
        customer_id,
        MAX(order_date::date) AS last_order_date,
        SUM(sales) AS lifetime_sales
    FROM sales
    GROUP BY customer_id
)
SELECT 
