ORDER BY order_count DESC;
-- Insight: Identifies customer shipping preferences. Standard Class is typically the most popular due to cost efficiency.

-- Q4: What is the average order value (AOV)?
-- SQL:
WITH order_totals AS (
    SELECT order_id, SUM(sales) AS order_sales
    FROM sales
    GROUP BY order_id
)
SELECT ROUND(AVG(order_sales)::numeric, 2) AS average_order_value
FROM order_totals;
-- Insight: Crucial marketing KPI. A higher AOV means customers are buying more expensive items or bundle packs.

-- Q5: Which product categories are sold and what is their average discount?
