-- Q1: What is the total revenue and net profit generated by the business?
-- SQL:
SELECT 
    ROUND(SUM(sales)::numeric, 2) AS total_revenue,
    ROUND(SUM(profit)::numeric, 2) AS total_profit
FROM sales;
-- Insight: Establishes the business baseline. Net profit is critical to evaluate if top-line revenue growth translates to actual earnings.

-- Q2: Find the total number of unique orders and unique customers.
-- SQL:
SELECT 
    COUNT(DISTINCT order_id) AS total_orders,
    COUNT(DISTINCT customer_id) AS total_customers
FROM sales;
-- Insight: Helps evaluate customer frequency. If order count is much higher than customer count, customer loyalty and repeat purchases are strong.

-- Q3: List the unique ship modes available and how many orders used each.
-- SQL:
